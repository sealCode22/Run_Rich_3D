using UnityEngine;

public sealed class ReferenceDoor : ReferencePickup
{
    // =========================================================
    // DOOR
    // =========================================================

    [Header("Door")]
    [SerializeField]
    private ReferenceDoor relatedDoor;

    // =========================================================
    // AWAKE
    // =========================================================

    protected override void Awake()
    {
        base.Awake();

        // Дверь не должна вращаться
        // и плавать как обычный Pickup.
    }

    // =========================================================
    // COLLECT
    // =========================================================

    protected override void Collect()
    {
        // -----------------------------------------------------
        // PROTECTION
        // -----------------------------------------------------

        if (relatedDoor == null)
        {
            Debug.LogWarning(
                "ReferenceDoor: " +
                "Related Door не назначен.",
                this
            );
        }

        // -----------------------------------------------------
        // STATUS
        // -----------------------------------------------------

        ApplyStatus();

        // -----------------------------------------------------
        // DISABLE CURRENT DOOR TRIGGER
        // -----------------------------------------------------

        if (pickupCollider != null)
        {
            pickupCollider.enabled = false;
        }

        // -----------------------------------------------------
        // REMOVE RELATED DOOR
        // -----------------------------------------------------

        if (relatedDoor != null)
        {
            if (relatedDoor == this)
            {
                Debug.LogError(
                    "ReferenceDoor: " +
                    "Related Door ссылается на саму себя!",
                    this
                );
            }
            else
            {
                Destroy(
                    relatedDoor.gameObject
                );
            }
        }

        // -----------------------------------------------------
        // IMPORTANT
        // -----------------------------------------------------
        //
        // Свою дверь НЕ уничтожаем.
        // Анимацию Pickup тоже НЕ запускаем.
        //
        // Поэтому дверь остается на сцене.
    }
}